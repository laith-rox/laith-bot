def visual_kind_for_lesson(lesson):
    """Map a research lesson to a compact educational diagram family."""
    title = str((lesson or {}).get("title") or "")
    if any(x in title for x in ("الخبر", "ردة فعل")):
        return "event"
    if any(x in title for x in ("التقلب", "الستوب", "المخاطرة", "السحب")):
        return "volatility"
    if any(x in title for x in ("اختراق", "الكسر")):
        return "breakout"
    if any(x in title for x in ("السيولة", "الإلكتروني", "Bid", "Ask", "السبريد", "أوامر", "اللوت", "الرافعة", "الهامش")):
        return "execution"
    if any(x in title for x in ("جلسة",)):
        return "sessions"
    if any(x in title for x in ("COT", "التمركز")):
        return "positioning"
    if any(x in title for x in ("التوقع الرياضي", "نسبة النجاح", "البقاء")):
        return "expectancy"
    if any(x in title for x in ("اختبار الماضي",)):
        return "backtest"
    if any(x in title for x in ("مصفوفة", "سببي", "الارتباط")):
        return "matrix"
    if any(x in title for x in ("الصفقة الجيدة", "أين أنا غلطان", "الانتظار", "الرابحين")):
        return "process"
    if any(x in title for x in ("الترند", "الإطار", "الفريم", "المكان", "التمدد", "النظام السوقي", "الاتجاه", "الدعم", "المقاومة", "الشمعة", "التداول", "تقرأ سوق", "BUY", "SELL")):
        return "trend"
    return "structure"


